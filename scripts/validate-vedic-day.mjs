import assert from "node:assert/strict";
import { daylightVedicWindows } from "../src/lib/vedic-windows.ts";

const sun=daylightVedicWindows({date:"2026-11-22",sunrise:"06:00",sunset:"18:00"});
assert.equal(sun.status,"calculated");
assert.equal(sun.weekday,"Sunday");
assert.equal(sun.choghadiya.length,8);
assert.equal(sun.hora.length,12);
assert.equal(sun.choghadiya[0].name,"Udveg");
assert.equal(sun.choghadiya[0].start,"06:00");
assert.equal(sun.choghadiya[0].end,"07:30");
assert.equal(sun.choghadiya[7].end,"18:00");
assert.equal(sun.hora[0].name,"Sun");
assert.equal(sun.hora[1].name,"Venus");
assert.equal(sun.hora[0].end,"07:00");
assert.deepEqual([sun.rahuKala?.start,sun.rahuKala?.end],["16:30","18:00"]);
assert.deepEqual([sun.abhijit?.start,sun.abhijit?.end],["11:36","12:24"]);
const mon=daylightVedicWindows({date:"2026-11-23",sunrise:"06:00",sunset:"18:00"});
assert.equal(mon.weekday,"Monday");
assert.equal(mon.choghadiya[0].name,"Amrit");
assert.equal(mon.hora[0].name,"Moon");
assert.deepEqual([mon.rahuKala?.start,mon.rahuKala?.end],["07:30","09:00"]);
const wed=daylightVedicWindows({date:"2026-11-25",sunrise:"06:00",sunset:"18:00"});
assert.deepEqual([wed.rahuKala?.start,wed.rahuKala?.end],["12:00","13:30"]);
assert.match(wed.warning,/Wednesdays/);
const missing=daylightVedicWindows({date:"2026-11-25",sunrise:null,sunset:"18:00"});
assert.equal(missing.status,"unavailable");
assert.equal(missing.rahuKala,null);
assert.deepEqual(missing.choghadiya,[]);
assert.equal(daylightVedicWindows({date:"2026-11-25",sunrise:"18:00",sunset:"06:00"}).status,"unavailable");
assert.equal(daylightVedicWindows({date:"2026-11-25",sunrise:"invalid",sunset:"18:00"}).status,"unavailable");
assert.throws(()=>daylightVedicWindows({date:"2026-02-30",sunrise:"06:00",sunset:"18:00"}),/valid Gregorian/);
console.log("Vedic daily window regression checks passed (Sunday, Monday, Wednesday, missing solar events, invalid dates).");
